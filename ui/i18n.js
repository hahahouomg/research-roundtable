try { if (localStorage.getItem(languageKey) === "en") language = "en"; } catch {}
function uiLanguage(){ return language; }
function setUiLanguage(value){
  language = value === "en" ? "en" : "zh-CN";
  try { localStorage.setItem(languageKey, language); } catch {}
}
function t(message, values = {}){
  const pattern = language === "en" && Object.hasOwn(english, message) ? english[message] : message;
  return String(pattern ?? "").replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? values[key] : match);
}
function translateShell(){
  document.documentElement.lang = language;
  document.title = t("Roundtable · 科研圆桌");
  document.getElementById("language").value = language;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const attr of ["aria-label", "title", "placeholder"]){
    document.querySelectorAll("[data-i18n-"+attr+"]").forEach(el => {
      el.setAttribute(attr, t(el.getAttribute("data-i18n-"+attr)));
    });
  }
}
